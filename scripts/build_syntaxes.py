"""Write the CSV syntaxes, one per delimiter, with a colour per column."""

import os
from typing import List, Tuple

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

# Scopes that common colour schemes give distinct foregrounds. Columns cycle
# through them, so column 8 looks like column 1.
COLUMN_SCOPES = [
    "variable.other",
    "keyword.control",
    "string.unquoted",
    "constant.numeric",
    "entity.name.function",
    "entity.name.tag",
    "support.type",
]

# (file name, syntax name, delimiter regex, hidden, file extensions)
SYNTAXES: List[Tuple[str, str, str, bool, List[str]]] = [
    ("CSV.sublime-syntax", "CSV", ",", False, ["csv"]),
    ("CSV (Semicolon).sublime-syntax", "CSV (Semicolon)", ";", True, []),
    ("CSV (Tab).sublime-syntax", "CSV (Tab)", "\\t", False, ["tsv"]),
    ("CSV (Pipe).sublime-syntax", "CSV (Pipe)", "\\|", True, []),
]


def render(name: str, delimiter: str, hidden: bool, extensions: List[str]) -> str:
    """Return the sublime-syntax text for one delimiter."""
    lines = [
        "%YAML 1.2",
        "---",
        "# Generated by scripts/build_syntaxes.py. Do not edit.",
        f"name: {name}",
    ]
    if extensions:
        lines.append("file_extensions:")
        lines.extend(f"  - {extension}" for extension in extensions)
    if hidden:
        lines.append("hidden: true")
    lines.extend(
        [
            "scope: text.csv",
            "",
            "variables:",
            f"  delimiter: '{delimiter}'",
            "  field_start: '(?:^|(?<={{delimiter}})) *'",
            "",
            "contexts:",
            "  main:",
            "    - match: '^'",
            "      push: column_1",
        ]
    )
    count = len(COLUMN_SCOPES)
    for number, scope in enumerate(COLUMN_SCOPES, start=1):
        following = number % count + 1
        color = f"{scope}.column-{number}.csv"
        lines.extend(
            [
                "",
                f"  column_{number}:",
                f"    - meta_content_scope: meta.column.{number}.csv",
                "    - match: '{{field_start}}(\")'",
                "      captures:",
                "        1: punctuation.definition.string.begin.csv",
                f"      push: double_quoted_{number}",
                "    - match: \"{{field_start}}(')\"",
                "      captures:",
                "        1: punctuation.definition.string.begin.csv",
                f"      push: single_quoted_{number}",
                "    - match: '{{delimiter}}'",
                "      scope: punctuation.separator.sequence.csv",
                f"      set: column_{following}",
                "    - match: '\\n'",
                "      pop: true",
                "    - match: '[^\\n]+?(?={{delimiter}}|\\n|$)'",
                f"      scope: {color}",
            ]
        )
        for kind, quote, yaml_quote in (("double", '"', "'"), ("single", "'", '"')):
            lines.extend(
                [
                    "",
                    f"  {kind}_quoted_{number}:",
                    f"    - meta_scope: string.quoted.{kind}.csv {color}",
                    f"    - match: {yaml_quote}{quote * 2}{yaml_quote}",
                    "      scope: constant.character.escape.csv",
                    f"    - match: {yaml_quote}{quote}{yaml_quote}",
                    "      scope: punctuation.definition.string.end.csv",
                    "      pop: true",
                ]
            )
    return "\n".join(lines) + "\n"


def outputs() -> List[Tuple[str, str]]:
    """Return (path, text) for every syntax file."""
    return [
        (os.path.join(ROOT, file_name), render(name, delimiter, hidden, extensions))
        for file_name, name, delimiter, hidden, extensions in SYNTAXES
    ]


def main() -> None:
    for path, text in outputs():
        with open(path, "w", encoding="utf-8", newline="\n") as handle:
            handle.write(text)


if __name__ == "__main__":
    main()
